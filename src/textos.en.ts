// 1st, 2nd, 3rd, 4th…
function ordinal(n: number): string {
  const resto = n % 100
  if (resto >= 11 && resto <= 13) return `${n}th`
  return `${n}${({ 1: 'st', 2: 'nd', 3: 'rd' } as Record<number, string>)[n % 10] ?? 'th'}`
}

